#!/usr/bin/env python3
"""Generate god entry surfaces from the strictly typed canonical ownership table."""

from __future__ import annotations

import argparse
from dataclasses import dataclass, fields
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "harness/gods.toml"


@dataclass(frozen=True)
class God:
    name: str
    korean: str
    purpose_en: str
    purpose_ko: str
    summary_en: str
    summary_ko: str
    ownership_ko: str
    role: str
    aliases: list[str]
    commands: list[str]
    skills: list[str]
    steps: list[str]

    @property
    def title(self) -> str:
        return self.name.capitalize()

    @property
    def names(self) -> str:
        return ", ".join([self.name, self.korean, *self.aliases])

    @property
    def description_en(self) -> str:
        # What the Skill does comes first; the names only decide when it is called.
        return f"({self.name}) {self.summary_en} Use only when the user names {self.names}."

    @property
    def description_ko(self) -> str:
        return f"({self.name}) {self.summary_ko}. 사용자가 {self.names} 중 하나를 부를 때만 사용."


def load_table(path: Path = TABLE) -> list[God]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    if set(data) != {"schema_version", "gods"} or data["schema_version"] != 1:
        raise ValueError("invalid god table schema")
    result = []
    scalar = {"name", "korean", "purpose_en", "purpose_ko", "summary_en", "summary_ko", "ownership_ko", "role"}
    for row in data["gods"]:
        if set(row) != {field.name for field in fields(God)}:
            raise ValueError("unknown or missing god field")
        for key, value in row.items():
            if key in scalar:
                valid = isinstance(value, str) and bool(value)
            else:
                valid = isinstance(value, list) and all(isinstance(v, str) and v for v in value)
            if not valid:
                raise ValueError(f"invalid god field type: {key}")
        result.append(God(**row))
    if any(not re.fullmatch(r"[a-z][a-z0-9-]*", god.name) for god in result):
        raise ValueError("god name must be a safe relative directory slug")
    for field in ("name", "commands", "skills"):
        values = [value for god in result for value in ([god.name] if field == "name" else getattr(god, field))]
        if len(values) != len(set(values)):
            raise ValueError(f"duplicate god ownership: {field}")
    names = [name.lower() for god in result for name in [god.name, god.korean, *god.aliases]]
    if len(names) != len(set(names)):
        raise ValueError("duplicate god alias")
    if len(result) != 9 or any(god.name not in god.skills for god in result):
        raise ValueError("expected nine self-owned god entries")
    return result


def quote(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def rust_table(gods: list[God]) -> str:
    text = "// Generated by scripts/generate-gods.py from harness/gods.toml.\n"
    text += "pub const GODS: &[God] = &[\n"
    for god in gods:
        text += "    God {\n"
        values = {key: getattr(god, key) for key in ("name", "korean", "purpose_en", "purpose_ko", "role")}
        values.update(display_name=god.title, description_en=god.description_en, description_ko=god.description_ko)
        for key, value in values.items():
            text += f"        {key}: {quote(value)},\n"
        for key in ("aliases", "commands"):
            text += f"        {key}: &[" + ", ".join(quote(v) for v in getattr(god, key)) + "],\n"
        text += "    },\n"
    text += "];\n"
    rustfmt = shutil.which("rustfmt") or str(Path.home() / ".cargo/bin/rustfmt.exe")
    return subprocess.run([rustfmt, "--edition", "2021"], input=text, text=True, encoding="utf-8", capture_output=True, check=True).stdout


def skill_text(god: God) -> str:
    steps = ["Read the project's AGENTS.md and preserve its scope, authority and usage boundaries."]
    routed = [name for name in god.skills if name != god.name]
    if routed:
        steps.append("Open only the relevant owned Skill: " + ", ".join(f"[{name}](../{name}/SKILL.md)" for name in routed) + ". Follow its procedure; this entry grants no additional authority.")
    steps.extend(god.steps)
    if god.name == "poseidon":
        steps.append("Keep model calls and process launch host-owned. New orchestration stays disabled until qualified host receipts, cancellation and reclaim exist.")
    return (
        f"---\nname: {god.name}\ndescription: {quote(god.description_en)}\n---\n\n"
        f"# {god.title}\n\n"
        "<!-- Generated from harness/gods.toml by scripts/generate-gods.py. -->\n\n"
        f"Use this entry only when the user names {god.names}. Generic task requests use the existing task-specific Skills.\n\n"
        f"At entry, announce in the user-selected response language: English `Calling upon {god.title} — {god.purpose_en}`; Korean `{god.korean} 호출 — {god.purpose_ko}`. CLI display prefix: `[{god.title}]`. Preserve JSON stdout; display notices on stderr.\n\n"
        + "\n".join(f"{index}. {step}" for index, step in enumerate(steps, 1)) + "\n"
    )


def metadata(god: God) -> str:
    return (
        f"interface:\n  display_name: {quote(god.title)}\n"
        f"  short_description: {quote(god.description_en)}\n"
        f"  default_prompt: {quote('Use $aigent-hive:' + god.name + ' as explicitly requested.')}\n"
        "policy:\n  allow_implicit_invocation: true\n"
    )


def outputs(gods: list[God]) -> dict[Path, str]:
    result = {ROOT / "crates/hive-core/src/gods_generated.rs": rust_table(gods)}
    for god in gods:
        for base, companion in (
            ("harness/skills", True),
            ("harness/plugins/aigent-hive/skills", True),
            ("harness/template/.agents/skills", True),
            ("harness/template/.claude/skills", False),
        ):
            result[ROOT / base / god.name / "SKILL.md"] = skill_text(god)
            if companion:
                result[ROOT / base / god.name / "agents/openai.yaml"] = metadata(god)
    doc = ROOT / "docs/architecture/god-ownership.md"
    text = doc.read_text(encoding="utf-8")
    start = text.index("| 정본 |")
    end = text.index("\n## 역할 기본값", start)
    table = "| 정본 | 맡는 일 | CLI 명령 | Skill |\n| --- | --- | --- | --- |\n"
    for god in gods:
        table += f"| {god.name} | {god.ownership_ko} | " + ", ".join(f"`{s}`" for s in god.commands) + " | " + ", ".join(f"`{s}`" for s in god.skills) + " |\n"
    result[doc] = text[:start] + table + text[end:]
    guide = ROOT / "docs/skills.md"
    text = guide.read_text(encoding="utf-8")
    for god in gods:
        row = f"| `{god.name}` | {god.summary_ko} | {god.korean} 호출 |"
        text, count = re.subn(rf"(?m)^\| `{re.escape(god.name)}` \|[^\n]*$", row, text)
        if count != 1:
            raise ValueError(f"expected one god guide row: {god.name}")
    result[guide] = text
    ledger = ROOT / "harness/template/.hive/config/active-skills.yml.jinja"
    text = ledger.read_text(encoding="utf-8")
    for god in gods:
        digest = hashlib.sha256(skill_text(god).encode()).hexdigest()
        text = re.sub(rf"(- name: {god.name}\n  source_type: built-in\n  content_digest: sha256:)[a-f0-9]{{64}}", lambda m: m[1] + digest, text)
    result[ledger] = text
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    generated = outputs(load_table())
    for path, content in generated.items():
        expected = content.encode("utf-8")
        if not path.exists() or path.read_bytes() != expected:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(expected)
    if args.check and stale:
        print("Stale god surfaces:\n" + "\n".join(stale))
        return 1
    print(f"God surfaces {'checked' if args.check else 'generated'}: {len(generated)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
